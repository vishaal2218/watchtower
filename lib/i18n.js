const TABLES = { en, ja };

function pickLocale(hostLocale) {
  return /^ja/i.test(String(hostLocale || '')) ? 'ja' : 'en';
}

function createTranslator(locale) {
  const table = TABLES[locale] || en;
  return function t(key, vars) {
    const template = table[key] !== undefined ? table[key] : en[key] !== undefined ? en[key] : key;
    return String(template).replace(/\{(\w+)\}/g, (m, name) =>
      vars && vars[name] !== undefined ? String(vars[name]) : m
    );
  };
}

module.exports = { TABLES, pickLocale, createTranslator };
